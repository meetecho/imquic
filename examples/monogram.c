static uint monogram_bitmap_png_len = 1376;

/* Font texture */
static SDL_Texture *font = NULL;

/* Helper to load the embedded font */
int monogram_load_font(SDL_Renderer *renderer) {
	if(font != NULL)
		monogram_unload_font();
	/* Open the embedded monogram font, for text rendering */
	SDL_RWops *rw = SDL_RWFromConstMem(monogram_bitmap_png, monogram_bitmap_png_len);
	if(rw == NULL) {
		IMQUIC_LOG(IMQUIC_LOG_ERR, "Error reading font data: %s\n", SDL_GetError());
		return -1;
	}
	SDL_Surface *surface = IMG_Load_RW(rw, 1);
	if(surface == NULL) {
		IMQUIC_LOG(IMQUIC_LOG_ERR, "Error opening font image: %s\n", SDL_GetError());
		return -2;
	}
	font = SDL_CreateTextureFromSurface(renderer, surface);
	SDL_FreeSurface(surface);
	return 0;
}

/* Helper to get rid of embedded font */
void monogram_unload_font(void) {
	if(font != NULL)
		SDL_DestroyTexture(font);
	font = NULL;
}

/* Helper to write text */
int monogram_write(SDL_Renderer *renderer, const char *text,
		int x, int y, float scale, int screen_w, int screen_h) {
	if(font == NULL || text == NULL)
		return -1;
	size_t len = strlen(text);
	if(len == 0)
		return 0;
	/* Iterate on all characters */
	size_t i = 0, col = 0;
	int f_x = 0, f_y = 0;
	SDL_Rect from = { 0 };
	SDL_FRect to = { 0 };
	for(i=0; i<len; i++) {
		if(text[i] < 32)
			continue;
		/* Find the character in the bitmap */
		f_x = (text[i] - 32) % (MONOGRAM_FONT_WIDTH / MONOGRAM_GLYPH_WIDTH);
		f_y = (text[i] - 32) / (MONOGRAM_FONT_WIDTH / MONOGRAM_GLYPH_WIDTH);
		/* Render the character at the right coordinates */
		from.x = f_x * MONOGRAM_GLYPH_WIDTH;
		from.y = f_y * MONOGRAM_GLYPH_HEIGHT;
		from.w = MONOGRAM_GLYPH_WIDTH;
		from.h = MONOGRAM_GLYPH_HEIGHT;
		to.x = x + (col * MONOGRAM_GLYPH_WIDTH * scale);
		to.y = y;
		to.w = MONOGRAM_GLYPH_WIDTH * scale;
		to.h = MONOGRAM_GLYPH_HEIGHT * scale;
		if((to.x + to.w) < screen_w && (to.y + to.h) < screen_h)
			SDL_RenderCopyF(renderer, font, &from, &to);
		/* Move on */
		col++;
	}
	/* Done */
	return 0;
}
